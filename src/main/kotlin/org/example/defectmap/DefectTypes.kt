package org.example.defectmap

object DefectTypes {
    // ===== ДИНАМИЧЕСКИЙ СПИСОК =====
    private var _allTypes: MutableList<String> = mutableListOf()

    val ALL_TYPES: List<String>
        get() = _allTypes.toList()

    // ===== ЗАГРУЗКА ИЗ БД =====
    fun loadFromDatabase(database: Database) {
        val types = database.loadAllDefectTypes()
        if (types.isNotEmpty()) {
            _allTypes.clear()
            _allTypes.addAll(types)
            println("✅ Загружено ${_allTypes.size} видов дефектов из БД")
        } else {
            println("ℹ️ Таблица defect_types пуста, загружаем дефолтные значения")
            loadDefaults()
        }
    }

    fun loadDefaults() {
        _allTypes.clear()
        _allTypes.addAll(defaultTypes)
        println("✅ Загружено ${_allTypes.size} дефолтных видов дефектов")
    }

    fun reloadDefaults() = loadDefaults()

    fun getDefaultTypes(): List<String> = defaultTypes.toList()

    // ===== ДИНАМИЧЕСКОЕ УПРАВЛЕНИЕ =====
    fun addType(name: String) {
        if (!_allTypes.contains(name)) {
            _allTypes.add(name)
            println("➕ Добавлен вид дефекта: $name")
        }
    }

    fun removeType(name: String) {
        _allTypes.remove(name)
        println("🗑️ Удалён вид дефекта: $name")
    }

